package io.agenticdb.jdbc;

import io.agenticdb.model.ColumnSpec;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * D-3：Oracle 方言的差异点门禁。
 *
 * <p>钉住四处「照搬别家就错」的地方：双引号 + 大写标识符的习惯、内联视图别名
 * <b>不带 {@code AS}</b>、{@code ADD (…) } 的括号、外键只有 {@code ON DELETE}。
 *
 * <p>⚠️ 元数据 SQL（ALL_TABLES / USER_CONSTRAINTS 等）本轮没有真库，
 * 这里只钉拼装结果；真库验证走 {@link RealDatabaseContract}（需要 Docker，本机没有）。
 */
class OracleDialectTest {

    private final OracleDialect dialect = new OracleDialect();

    @Test
    void itIsItsOwnKindWithItsOwnDriverAndPort() {
        assertThat(dialect.kind()).isEqualTo(DialectKind.ORACLE);
        assertThat(dialect.displayName()).isEqualTo("Oracle");
        assertThat(dialect.driverClassName()).isEqualTo("oracle.jdbc.OracleDriver");
        assertThat(dialect.defaultPort()).isEqualTo(1521);
        assertThat(dialect.uriScheme()).isEqualTo("oracle");
    }

    @Test
    void identifiersUseDoubleQuotesLikePostgres() {
        assertThat(dialect.quote("users")).isEqualTo("\"users\"");
        assertThat(dialect.quote("a\"b")).isEqualTo("\"a\"\"b\"");
    }

    @Test
    void jdbcUrlIsTheEzConnectFormAndTimeoutsArePropertiesNotUrl() {
        assertThat(dialect.jdbcUrl("db.local", 1521, "ORCLPDB"))
                .isEqualTo("jdbc:oracle:thin:@//db.local:1521/ORCLPDB");
        // Oracle 的超时参数只能走 Properties（ojdbc11 支持这两个键，单位都是毫秒）。
        assertThat(dialect.connectionProperties())
                .containsEntry("oracle.net.CONNECT_TIMEOUT", "10000")
                .containsEntry("oracle.jdbc.ReadTimeout", "30000");
    }

    @Test
    void pagingUsesOffsetFetchAndTheInlineViewAliasHasNoAs() {
        assertThat(dialect.pagingClause(20, 40, false))
                .isEqualTo(" OFFSET 40 ROWS FETCH NEXT 20 ROWS ONLY");
        Dialect.PagedSql page = dialect.pagedSelect(
                "SELECT * FROM \"USERS\" ORDER BY id", List.of(), 20, 40);
        assertThat(page.sql())
                .as(") AS _p 在 Oracle 是语法错误，只能 ) _p")
                .isEqualTo("SELECT * FROM (SELECT * FROM \"USERS\" ORDER BY id) _p"
                        + " OFFSET ? ROWS FETCH NEXT ? ROWS ONLY");
        assertThat(page.params()).containsExactly(40, 20);

        Dialect.PagedSql count = dialect.countedSelect("SELECT * FROM \"USERS\"", List.of());
        assertThat(count.sql())
                .isEqualTo("SELECT COUNT(*) AS adb_count FROM (SELECT * FROM \"USERS\") _p");
    }

    @Test
    void emptyPageProbeUsesRownumInsteadOfLimit() {
        assertThat(dialect.probeColumnsSql("users"))
                .isEqualTo("SELECT * FROM \"users\" WHERE ROWNUM = 0");
    }

    @Test
    void addColumnNeedsParenthesesAndIdentityReplacesDefault() {
        ColumnSpec note = new ColumnSpec("note", "VARCHAR2(100)", true, null, null,
                false, false);
        assertThat(dialect.addColumnSql("users", note))
                .isEqualTo("ALTER TABLE \"users\" ADD (\"note\" VARCHAR2(100))");

        ColumnSpec id = new ColumnSpec("id", "BIGINT", false, null, null, false, true,
                true, null, null);
        assertThat(dialect.columnDefinition(id, true))
                .isEqualTo("\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL");
    }

    @Test
    void foreignKeysHaveNoOnUpdate() {
        assertThat(dialect.supportsForeignKeyOnUpdate()).isFalse();
        String sql = dialect.addForeignKeySql("orders", "fk_user", List.of("user_id"),
                "users", List.of("id"), "CASCADE", "SET NULL");
        assertThat(sql)
                .as("Oracle 的外键只有 ON DELETE；把界面的 ON UPDATE 塞进去会直接报错")
                .isEqualTo("ALTER TABLE \"orders\" ADD CONSTRAINT \"fk_user\" "
                        + "FOREIGN KEY (user_id) REFERENCES \"users\" (id) ON DELETE SET NULL");
        assertThat(sql).doesNotContain("ON UPDATE");
    }

    @Test
    void catalogAndSchemaFollowOraclesModel() {
        assertThat(dialect.hasCatalog()).as("Oracle 没有 catalog 这一层").isFalse();
        assertThat(dialect.hasSchema()).isTrue();
        assertThat(dialect.setSchemaSql("APP"))
                .isEqualTo("ALTER SESSION SET CURRENT_SCHEMA = APP");
    }

    @Test
    void capabilitiesThatNeedATwoStepProtocolAreDeclaredNotFaked() {
        assertThat(dialect.supportsExplainPlan()).isFalse();
        assertThatThrownBy(() -> dialect.explainSql("SELECT 1"))
                .isInstanceOf(UnsupportedOperationException.class);
        assertThat(dialect.supportsSslOptionsUi()).isFalse();
        assertThat(dialect.sslOptionsNoticeKey())
                .as("说明文案在资源包里；正文由界面的向导测试对账")
                .isEqualTo("wizard.ssl.notice.oracle");
        assertThat(dialect.supportsColumnComment()).isTrue();
        assertThat(dialect.minVersionNote()).contains("12c");
    }

    /**
     * ⭐ D-22 的门禁：目录查询必须<b>同时</b>认「原样」和「大写」两种存法。
     *
     * <p>这条是 R46 在 Oracle 23ai Free 真容器上跑出来的：设计器建表一律加引号，
     * Oracle 就把名字原样存进目录；而这几条查询以前只写 {@code = UPPER(?)}，
     * 实测 {@code TABLE_NAME='adb_case_probe'} 命中 1 行、{@code =UPPER(...)} 命中 0 行 ——
     * 于是<b>我们自己建出来的表</b>在触发器页、约束页、注释页里全部隐形。
     * 界面不会报错，只会显示「没有触发器 / 没有约束 / 没有注释」——
     * 这正是「看起来是真的但什么都不做」的那类缺陷。
     */
    @Test
    void dictionaryLookupsMatchBothTheStoredAndFoldedName() {
        assertThat(dialect.triggersSql("orders"))
                .as("触发器：原样 + 大写两个都要认")
                .contains("TABLE_NAME IN (?, UPPER(?))");
        assertThat(dialect.tableCommentQuery("orders"))
                .as("表注释：原样 + 大写两个都要认")
                .contains("TABLE_NAME IN (?, UPPER(?))");
        assertThat(dialect.checksSql("orders"))
                .as("CHECK 约束：原样 + 大写两个都要认")
                .contains("c.TABLE_NAME IN (?, UPPER(?))");

        // 只剩 UPPER 的写法一律算回归：它只会命中「没加引号建」的对象。
        for (String sql : List.of(dialect.triggersSql("orders"),
                dialect.tableCommentQuery("orders"), dialect.checksSql("orders"))) {
            assertThat(sql)
                    .as("目录查询不许再出现「只按大写匹配」：%s", sql)
                    .doesNotContain("= UPPER(?)");
        }
    }

    /**
     * ⭐ D-22 的内联通道：{@code columnCommentsSql} 的表名不进参数，得自己拼两个字面量。
     *
     * <p>顺带钉住转义 —— 名字里的 {@code '} 要写两遍，否则拼出来的是一条坏 SQL
     * （更糟的情况是可注入）。
     */
    @Test
    void inlinedColumnCommentLookupCarriesBothFormsAndEscapesTheQuote() {
        assertThat(dialect.columnCommentsSql("orders"))
                .contains("TABLE_NAME IN ('orders', 'ORDERS')");

        assertThat(dialect.columnCommentsSql("o'brien"))
                .as("转义先做大写后做都行，但引号必须成对 —— 这条通道的名字是内联的")
                .contains("TABLE_NAME IN ('o''brien', 'O''BRIEN')");
    }

    /**
     * D-22：占位符数量变了（1 → 2），消费方必须按实际个数绑。
     *
     * <p>这里不做集成（要真连接），只把「两条 IN 各一个 {@code ?}」钉死，
     * 并让 {@code SchemaServiceTest} 用假连接验绑参次数 —— 少绑一次在 Oracle 上
     * 是 {@code ORA-01008 未所有变量都被绑定}，而那条异常在结构页被吞成「注释为空」，
     * 现场表现与「这个表真的没注释」完全一样。
     */
    @Test
    void nameMatchUsesTwoPlaceholdersSoTheCallerMustBindBoth() {
        assertThat(dialect.tableCommentQuery("orders").split("\\?", -1).length - 1)
                .as("表注释查询有 2 个占位符")
                .isEqualTo(2);
        assertThat(dialect.triggersSql("orders").split("\\?", -1).length - 1)
                .as("触发器查询有 2 个占位符")
                .isEqualTo(2);
        assertThat(dialect.checksSql("orders").split("\\?", -1).length - 1)
                .as("CHECK 查询有 2 个占位符")
                .isEqualTo(2);
    }
}
