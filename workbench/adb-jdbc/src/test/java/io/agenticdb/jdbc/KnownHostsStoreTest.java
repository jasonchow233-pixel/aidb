package io.agenticdb.jdbc;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Base64;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * ⭐ SSH 已知主机文件的解析/删除门禁。
 *
 * <p>这里不碰 {@code SshTunnel} 的 verifier：TOFU / strict 的安全判定有五套真库矩阵
 * 盯着，本轮只把「已记录的密钥」变得可见、可撤销，所以这一类必须能独立验证。
 */
class KnownHostsStoreTest {

    @TempDir
    Path temp;

    private static String key(String text) {
        return Base64.getEncoder().encodeToString(text.getBytes(StandardCharsets.UTF_8));
    }

    @Test
    void missingFileMeansNoHostKeysRecordedYet() throws Exception {
        assertThat(KnownHostsStore.read(temp.resolve("absent"))).isEmpty();
        assertThat(KnownHostsStore.read(null)).isEmpty();
    }

    @Test
    void readsStandardLinesAndSkipsCommentsAndBlankLines() throws Exception {
        Path file = temp.resolve("known_hosts");
        Files.writeString(file, String.join("\n", List.of(
                "# generated by AIDB",
                "",
                "bastion.example,10.0.0.1 ssh-ed25519 " + key("key-a") + " some comment",
                "other.example ssh-rsa " + key("key-b"))), StandardCharsets.UTF_8);

        List<KnownHostsStore.Entry> entries = KnownHostsStore.read(file);
        assertThat(entries).hasSize(2);
        assertThat(entries.get(0).lineNumber()).isEqualTo(3);
        assertThat(entries.get(0).host()).isEqualTo("bastion.example,10.0.0.1");
        assertThat(entries.get(0).keyType()).isEqualTo("ssh-ed25519");
        assertThat(entries.get(1).lineNumber()).isEqualTo(4);
        assertThat(entries.get(0).fingerprint()).startsWith("SHA256:");
        assertThat(entries.get(0).fingerprint()).isNotEqualTo(entries.get(1).fingerprint());
    }

    @Test
    void fingerprintIsStableAndInvalidKeysAreListedNotSilentlyDropped() {
        assertThat(KnownHostsStore.fingerprint(key("key-a")))
                .isEqualTo(KnownHostsStore.fingerprint(key("key-a")));
        assertThat(KnownHostsStore.fingerprint("not-base64!")).isEqualTo("unavailable");
        assertThat(KnownHostsStore.fingerprint("")).isEqualTo("unavailable");
        assertThat(KnownHostsStore.fingerprint(null)).isEqualTo("unavailable");
    }

    @Test
    void removeDeletesExactlyOneLineAndKeepsCommentsInPlace() throws Exception {
        Path file = temp.resolve("known_hosts");
        Files.writeString(file, String.join("\n", List.of(
                "# header",
                "a.example ssh-ed25519 " + key("key-a"),
                "b.example ssh-ed25519 " + key("key-b"),
                "",
                "c.example ssh-ed25519 " + key("key-c"))), StandardCharsets.UTF_8);

        KnownHostsStore.remove(file, 3);

        assertThat(Files.readAllLines(file, StandardCharsets.UTF_8)).containsExactly(
                "# header",
                "a.example ssh-ed25519 " + key("key-a"),
                "",
                "c.example ssh-ed25519 " + key("key-c"));
        assertThat(KnownHostsStore.read(file)).extracting(KnownHostsStore.Entry::host)
                .containsExactly("a.example", "c.example");
    }

    @Test
    void outOfRangeRemovalIsANoOp() throws Exception {
        Path file = temp.resolve("known_hosts");
        Files.writeString(file, "a.example ssh-ed25519 " + key("key-a"), StandardCharsets.UTF_8);
        String before = Files.readString(file, StandardCharsets.UTF_8);

        KnownHostsStore.remove(file, 99);
        KnownHostsStore.remove(file, 0);
        KnownHostsStore.remove(temp.resolve("absent"), 1);

        assertThat(Files.readString(file, StandardCharsets.UTF_8)).isEqualTo(before);
    }

    @Test
    void unreadableFileSurfacesAsAnIOExceptionForTheUiToExplain() throws Exception {
        Path file = temp.resolve("known_hosts");
        Files.writeString(file, "a.example ssh-ed25519 " + key("key-a"), StandardCharsets.UTF_8);
        // 目录当文件读：JDK 会抛 IOException，UI 应显示原因而不是假装文件为空。
        assertThat(Files.isDirectory(temp)).isTrue();
        org.assertj.core.api.Assertions.assertThatThrownBy(() -> KnownHostsStore.read(temp))
                .isInstanceOf(IOException.class);
        assertThat(KnownHostsStore.read(file)).hasSize(1);
    }
}
