package io.agenticdb.introspect;

import io.agenticdb.jdbc.DialectKind;
import io.agenticdb.model.ColumnSpec;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.regex.Pattern;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * ⭐ R31：建表时的列级选项 —— 自增 / 字符集 / 排序规则。
 *
 * <p>「建不出自增列」是 G15 的功能硬伤：MySQL / PostgreSQL 上手填主键等于建了一张
 * 不能直接用的表。三方言的写法完全不同，而且各自的<b>语序</b>都是硬要求
 * （MySQL 的 {@code AUTO_INCREMENT} 必须排在 {@code PRIMARY KEY} / {@code COMMENT} 之前），
 * 所以这里逐字锁死生成的 DDL。
 *
 * <p>另一半是<b>拒绝</b>：自增列不是主键、不是整型、带了默认值、SQLite 用了
 * {@code INT}、字符集写了非标识符 —— 每一条都必须在生成 SQL 之前给出中文原因。
 */
class CreateTableColumnOptionsTest {

    private static final ColumnSpec PK = new ColumnSpec("id", "INTEGER", false, null, null,
            false, true);

    // ─────────────────────────── 三方言的自增写法 ───────────────────────────

    @Test
    void mysqlPutsAutoIncrementBeforePrimaryKeyAndComment() {
        ColumnSpec column = new ColumnSpec("id", "INTEGER", false, null, "主键", false, true,
                true, null, null);

        String sql = plan(DialectKind.MYSQL, column).statements().getFirst();

        assertThat(sql).contains("`id` INTEGER NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT '主键'")
                .as("AUTO_INCREMENT 写在 PRIMARY KEY / COMMENT 之后是语法错误")
                .doesNotContain("PRIMARY KEY AUTO_INCREMENT");
    }

    @Test
    void postgresUsesIdentityBeforeNullOrOtherConstraints() {
        ColumnSpec column = new ColumnSpec("id", "INTEGER", false, "42", null, false, true,
                true, null, null);

        assertThatThrownBy(() -> plan(DialectKind.POSTGRESQL, column))
                .as("identity 列与默认值互斥，先拦在生成 SQL 之前")
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("默认值");

        String sql = plan(DialectKind.POSTGRESQL, new ColumnSpec("id", "INTEGER", false, null,
                null, false, true, true, null, null)).statements().getFirst();
        assertThat(sql).contains(
                "\"id\" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY");
    }

    @Test
    void sqliteUsesTheRowidAliasForm() {
        String sql = plan(DialectKind.SQLITE, new ColumnSpec("id", "INTEGER", false, null,
                null, false, true, true, null, null)).statements().getFirst();

        assertThat(sql).contains("\"id\" INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT")
                .as("SQLite 只有这一种写法能让自增真正生效");
    }

    // ─────────────────────────── 自增的拒绝规则 ───────────────────────────

    @Test
    void onlyOneColumnMayAutoIncrement() {
        assertThatThrownBy(() -> plan(DialectKind.MYSQL,
                new ColumnSpec("id", "INTEGER", false, null, null, false, true, true, null, null),
                new ColumnSpec("seq", "INTEGER", false, null, null, false, false, true, null, null)))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("只能有一列自增");
    }

    @Test
    void autoIncrementMustBeAPrimaryKey() {
        assertThatThrownBy(() -> plan(DialectKind.MYSQL,
                new ColumnSpec("seq", "INTEGER", false, null, null, false, false, true, null, null)))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("自增列必须是主键");
    }

    @Test
    void autoIncrementMustBeAnIntegerInEveryDialect() {
        for (DialectKind kind : DialectKind.values()) {
            // Oracle 的说法是「数值型」：IDENTITY 收 NUMBER / INTEGER，NUMBER 本身不是整型。
            String expected = kind == DialectKind.ORACLE ? "数值型" : "整型";
            assertThatThrownBy(() -> plan(kind,
                    new ColumnSpec("id", "TEXT", false, null, null, false, true, true, null, null)))
                    .as(kind + " 的自增列必须是整型")
                    .isInstanceOf(IllegalArgumentException.class)
                    .hasMessageContaining(expected);
        }
    }

    @Test
    void sqliteRequiresExactlyIntegerNotInt() {
        assertThatThrownBy(() -> plan(DialectKind.SQLITE,
                new ColumnSpec("id", "INT", false, null, null, false, true, true, null, null)))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("INTEGER");
    }

    @Test
    void postgresRejectsMySqlOnlyIntegerTypes() {
        assertThatThrownBy(() -> plan(DialectKind.POSTGRESQL,
                new ColumnSpec("id", "TINYINT", false, null, null, false, true, true, null, null)))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("smallint");
    }

    @Test
    void autoIncrementCannotCarryADefaultValue() {
        assertThatThrownBy(() -> plan(DialectKind.MYSQL,
                new ColumnSpec("id", "INTEGER", false, "0", null, false, true, true, null, null)))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("默认值");
    }

    @Test
    void sqliteAutoIncrementCannotBePartOfACompositeKey() {
        assertThatThrownBy(() -> plan(DialectKind.SQLITE,
                new ColumnSpec("id", "INTEGER", false, null, null, false, true, true, null, null),
                new ColumnSpec("tenant", "INTEGER", false, null, null, false, true, false, null, null)))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("唯一主键");
    }

    @Test
    void mysqlAutoIncrementMayLeadACompositeKey() {
        String sql = plan(DialectKind.MYSQL,
                new ColumnSpec("id", "INTEGER", false, null, null, false, true, true, null, null),
                new ColumnSpec("tenant", "INTEGER", false, null, null, false, true, false, null, null))
                .statements().getFirst();

        assertThat(sql).contains("`id` INTEGER NOT NULL AUTO_INCREMENT")
                .contains("PRIMARY KEY (`id`, `tenant`)");
    }

    // ─────────────────────────── 字符集 / 排序规则 ───────────────────────────

    @Test
    void columnCharsetExistsOnMySqlOnly() {
        ColumnSpec column = new ColumnSpec("name", "TEXT", true, null, null, false, false,
                false, "utf8mb4", "utf8mb4_bin");

        assertThat(plan(DialectKind.MYSQL, column).statements().getFirst())
                .contains("`name` TEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin");

        assertThatThrownBy(() -> plan(DialectKind.POSTGRESQL, column))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("字符集");
        assertThatThrownBy(() -> plan(DialectKind.SQLITE, column))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("字符集");
    }

    @Test
    void collationFollowsTheTypeInEveryDialect() {
        ColumnSpec mysql = new ColumnSpec("name", "TEXT", true, null, null, false, false,
                false, null, "utf8mb4_bin");
        ColumnSpec postgres = new ColumnSpec("name", "TEXT", true, null, null, false, false,
                false, null, "C");
        ColumnSpec sqlite = new ColumnSpec("name", "TEXT", true, null, null, false, false,
                false, null, "NOCASE");

        assertThat(plan(DialectKind.MYSQL, mysql).statements().getFirst())
                .contains("`name` TEXT COLLATE utf8mb4_bin");
        assertThat(plan(DialectKind.POSTGRESQL, postgres).statements().getFirst())
                .as("PostgreSQL 的排序规则是标识符，要带引号")
                .contains("\"name\" TEXT COLLATE \"C\"");
        assertThat(plan(DialectKind.SQLITE, sqlite).statements().getFirst())
                .contains("\"name\" TEXT COLLATE NOCASE");
    }

    @Test
    void charsetAndCollationMustBePlainIdentifiers() {
        assertThatThrownBy(() -> plan(DialectKind.MYSQL, new ColumnSpec("name", "TEXT", true,
                null, null, false, false, false, "utf8mb4; DROP TABLE users", null)))
                .as("字符集直接拼进 DDL —— 必须挡住语句注入")
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("字符集");

        assertThatThrownBy(() -> plan(DialectKind.MYSQL, new ColumnSpec("name", "TEXT", true,
                null, null, false, false, false, null, "utf8mb4'--")))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("排序规则");
    }

    private static StructurePlan plan(DialectKind kind, ColumnSpec... columns) {
        return StructureSqlBuilder.createTable(FakeDialectSession.of(kind), "users",
                List.of(columns), null, List.of());
    }

    /**
     * ⭐ R31：属性面板下拉里摆出来的<b>建议值</b>，建表器必须照收。
     *
     * <p>候选表住在方言层（UI 里判 {@code kind() == MYSQL} 会被
     * {@code DialectBranchAuditTest} 拦下），而校验住在这层 —— 两边一旦对不上，
     * 用户看到的就是「从下拉里挑了一个，结果报错」。
     */
    @Test
    void everyCharsetAndCollationPresetIsAcceptedByTheBuilder() {
        for (DialectKind kind : DialectKind.values()) {
            io.agenticdb.jdbc.Dialect dialect = kind.dialect();
            for (String charset : dialect.columnCharsetPresets()) {
                ColumnSpec column = new ColumnSpec("email", "VARCHAR(255)", true, null, null,
                        false, false, false, charset, null);
                assertThat(plan(kind, PK, column).statements().getFirst())
                        .as(kind + " 的字符集候选「" + charset + "」要能进 DDL")
                        .contains("CHARACTER SET " + charset);
            }
            for (String collation : dialect.columnCollationPresets()) {
                ColumnSpec column = new ColumnSpec("email", "VARCHAR(255)", true, null, null,
                        false, false, false, null, collation);
                assertThat(plan(kind, PK, column).statements().getFirst())
                        .as(kind + " 的排序规则候选「" + collation + "」要能进 DDL")
                        .containsPattern("COLLATE\\s*\"?" + Pattern.quote(collation) + "\"?");
            }
        }
    }
}
